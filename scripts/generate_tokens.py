#!/usr/bin/env python3
"""Generates azkarify/Shared/DesignSystem/AzkarifyTokens.swift from design/tokens/tokens.json.

tokens.json is copied unchanged from the Azkarify Design System artifact
(https://claude.ai/artifact/TxkT6itcDCauJ5EMTxR1VU, project/tokens.json). The Android
app generates its Kotlin tokens from the same file, so token names match across apps.

Usage: python3 scripts/generate_tokens.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design/tokens/tokens.json"
OUTPUT = ROOT / "azkarify/Shared/DesignSystem/AzkarifyTokens.swift"

# Dynamic Type anchor for each text style.
RELATIVE_TO = {
    "display": ".largeTitle", "title1": ".title", "title2": ".title2", "title3": ".title3",
    "headline": ".headline", "row-title": ".body", "body": ".body", "callout": ".callout",
    "footnote": ".footnote", "eyebrow": ".caption2", "button": ".body", "numeral": ".largeTitle",
    "reading-translation": ".body", "reading-arabic": ".body",
}

LATIN_FACES = {400: "SpaceGrotesk-Regular", 500: "SpaceGrotesk-Medium", 600: "SpaceGrotesk-SemiBold",
               700: "SpaceGrotesk-SemiBold"}
ARABIC_FACES = {400: "AlanSans-Regular", 500: "AlanSans-Medium", 600: "AlanSans-SemiBold",
                700: "AlanSans-Bold"}


def camel(name: str) -> str:
    head, *rest = re.split(r"[-_.]", name)
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def px(value) -> float:
    return float(str(value).replace("px", ""))


def hex_literal(value: str) -> str:
    value = value.lstrip("#")
    if len(value) == 3:
        value = "".join(c * 2 for c in value)
    return "0x" + value.upper()


def number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else f"{value:g}"


def style_metrics(style: dict) -> dict:
    size = px(style["fontSize"])
    tracking = str(style.get("letterSpacing", "0em"))
    tracking_value = float(tracking.replace("em", "")) * size if tracking.endswith("em") else px(tracking)
    return {
        "size": size,
        "line": px(style["lineHeight"]),
        "weight": int(style["fontWeight"]),
        "tracking": round(tracking_value, 3),
        "uppercase": style.get("textTransform") == "uppercase",
    }


def main() -> None:
    tokens = json.loads(SOURCE.read_text())
    out = [
        "// Generated by scripts/generate_tokens.py from design/tokens/tokens.json. Do not edit.",
        "// Source: Azkarify Design System (Day = light, Night = dark).",
        "",
        "import SwiftUI",
        "import UIKit",
        "",
        "enum AZColor {",
    ]
    for token in tokens["color"]["tokens"]:
        value = token["value"]
        light, dark = (value, value) if isinstance(value, str) else (value["light"], value.get("dark", value["light"]))
        out.append(f"  /// {token.get('usage', '').strip()}")
        out.append(
            f"  static let {camel(token['name'])} = Color(uiColor: UIColor(light: {hex_literal(light)}, dark: {hex_literal(dark)}))")
    out.append("}")
    out.append("")

    for family, enum in (("spacing", "AZSpace"), ("radius", "AZRadius"), ("border", "AZBorder")):
        out.append(f"enum {enum} {{")
        for token in tokens[family]["tokens"]:
            name = camel(re.sub(r"^(space|radius|border)-", "", token["name"]))
            out.append(f"  static let {name}: CGFloat = {number(px(token['value']))}")
        out.append("}")
        out.append("")

    out.append("enum AZDuration {")
    for token in tokens["duration"]["tokens"]:
        name = camel(token["name"].replace("duration-", ""))
        out.append(f"  static let {name}: Double = {number(px(token['value'].replace('ms', '')) / 1000)}")
    out.append("}")
    out.append("")

    out.append("/// Hard offset stamp shadows. The colour is `AZColor.stampShadow`; x mirrors in RTL.")
    out.append("enum AZStamp {")
    for token in tokens["shadow"]["tokens"]:
        value = token["value"]["light"] if isinstance(token["value"], dict) else token["value"]
        x, y = (px(part) for part in value.split()[:2])
        out.append(f"  static let {camel(token['name'].replace('stamp-', ''))} = CGSize(width: {number(x)}, height: {number(y)})")
    out.append("}")
    out.append("")

    latin, arabic = {}, {}
    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            name = style["name"]
            if name.startswith("ar-"):
                arabic[name[3:]] = style_metrics(style)
            else:
                latin[name] = style_metrics(style)

    names = list(dict.fromkeys(list(latin) + list(arabic)))
    out.append("enum AZTextStyle: CaseIterable {")
    out.append("  case " + ", ".join(camel(n) for n in names))
    out.append("")
    out.append("  struct Metrics {")
    out.append("    let face: String")
    out.append("    let size: CGFloat")
    out.append("    let lineHeight: CGFloat")
    out.append("    let tracking: CGFloat")
    out.append("    let uppercase: Bool")
    out.append("  }")
    out.append("")
    out.append("  var relativeTo: Font.TextStyle {")
    out.append("    switch self {")
    for n in names:
        out.append(f"    case .{camel(n)}: {RELATIVE_TO.get(n, '.body')}")
    out.append("    }")
    out.append("  }")
    out.append("")

    def metrics_literal(m: dict, faces: dict) -> str:
        return (f"Metrics(face: \"{faces[m['weight']]}\", size: {number(m['size'])}, "
                f"lineHeight: {number(m['line'])}, tracking: {number(m['tracking'])}, "
                f"uppercase: {'true' if m['uppercase'] else 'false'})")

    out.append("  /// Space Grotesk metrics for English UI. Arabic-only styles fall back to Alan Sans.")
    out.append("  var latin: Metrics {")
    out.append("    switch self {")
    for n in names:
        literal = metrics_literal(latin[n], LATIN_FACES) if n in latin else metrics_literal(arabic[n], ARABIC_FACES)
        out.append(f"    case .{camel(n)}: {literal}")
    out.append("    }")
    out.append("  }")
    out.append("")
    out.append("  /// Alan Sans metrics for Arabic UI: no tracking, no uppercase, taller lines.")
    out.append("  var arabic: Metrics {")
    out.append("    switch self {")
    for n in names:
        source = arabic.get(n) or {**latin[n], "tracking": 0, "uppercase": False}
        out.append(f"    case .{camel(n)}: {metrics_literal(source, ARABIC_FACES)}")
    out.append("    }")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("extension UIColor {")
    out.append("  convenience init(light: UInt32, dark: UInt32) {")
    out.append("    let lightColor = UIColor(hex: light)")
    out.append("    let darkColor = UIColor(hex: dark)")
    out.append("    self.init { $0.userInterfaceStyle == .dark ? darkColor : lightColor }")
    out.append("  }")
    out.append("")
    out.append("  convenience init(hex: UInt32) {")
    out.append("    self.init(")
    out.append("      red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,")
    out.append("      blue: CGFloat(hex & 0xFF) / 255, alpha: 1)")
    out.append("  }")
    out.append("}")
    out.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
